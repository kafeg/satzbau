import { expect, test } from 'vitest'
import { level, percent } from './rules.ts'

test('уровень по доле', () => {
  expect([1, 0.95, 0.949, 0.8, 0.79, 0.6, 0.599].map(level)).toEqual(['правило', 'правило', 'чаще всего', 'чаще всего', 'часто', 'часто', 'редко'])
})

test('проценты без лишней точности', () => {
  expect([1, 0.996, 0.99, 0.874, 0.599].map(percent)).toEqual(['100%', '99.6%', '99.0%', '87%', '59%'])
})
