// Что считается верным вводом. Правило живёт в ядре, а не в дрилле: по нему же
// засчитывает ответы симулятор ученика, и разойтись эти два места не должны.

import type { Item } from './types.ts'

const DIGRAPH: Record<string, string> = { ä: 'ae', ö: 'oe', ü: 'ue', ß: 'ss' }

/**
 * Ввод к сравнимому виду.
 *
 * ⚠ Умляуты принимаются диграфами: на телефоне без немецкой раскладки «ä» набрать
 * нечем, и минус за это был бы минусом за клавиатуру, а не за грамматику. Склеить
 * две разные формы это не может — проверено на всех заданиях: нормализация ни разу
 * не сравняла ответ с дистрактором (62 тысячи пар).
 *
 * ⚠ Пробелы: по краям снимаем, внутри сводим к одному. Ответ бывает из двух слов
 * («am schnellsten»), и лишний пробел в нём — не ошибка. Автодополнение на телефоне
 * дописывает пробел в конце само.
 */
export function normalize(s: string): string {
  return s
    .trim()
    .replace(/\s+/g, ' ')
    .toLowerCase()
    .replace(/[äöüß]/g, (c) => DIGRAPH[c] as string)
}

/** Принят ли ввод: сам ответ или любая из остальных верных форм (`answers`). */
export function accepts(item: Item, given: string): boolean {
  const g = normalize(given)
  return [item.answer, ...(item.answers ?? [])].some((a) => normalize(a) === g)
}
